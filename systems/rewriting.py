"""System A: words over a finite alphabet and string rewriting.

Words are Python strings whose characters are the symbols.  A rule is a pair
``(lhs, rhs)`` meaning ``x+lhs+y -> x+rhs+y``.  Nothing here uses arithmetic
on the objects themselves; integers appear only as loop bounds and as the
lengths that the *meta-level* analysis reports.
"""

from __future__ import annotations

import heapq
import itertools
from collections import deque

Rule = tuple[str, str]


# ---------------------------------------------------------------- basics
def occurrences(word: str, pat: str) -> list[int]:
    out, start = [], 0
    if not pat:
        return list(range(len(word) + 1))
    while True:
        i = word.find(pat, start)
        if i < 0:
            return out
        out.append(i)
        start = i + 1


def one_step(word: str, rules) -> list[str]:
    """All words reachable in exactly one rewrite step (with multiplicity per redex)."""
    out = []
    for lhs, rhs in rules:
        for i in occurrences(word, lhs):
            out.append(word[:i] + rhs + word[i + len(lhs):])
    return out


def is_irreducible(word: str, rules) -> bool:
    return all(lhs not in word for lhs, _ in rules)


def normal_form(word: str, rules, max_steps: int = 10**6) -> str:
    """Leftmost-redex normal form (well defined for terminating confluent systems)."""
    for _ in range(max_steps):
        best = None
        for lhs, rhs in rules:
            i = word.find(lhs)
            if i >= 0 and (best is None or i < best[0]):
                best = (i, lhs, rhs)
        if best is None:
            return word
        i, lhs, rhs = best
        word = word[:i] + rhs + word[i + len(lhs):]
    raise RuntimeError("normal_form: step limit exceeded (non-terminating system?)")


def words(alphabet: str, length: int):
    for t in itertools.product(alphabet, repeat=length):
        yield "".join(t)


def parikh(word: str, alphabet: str) -> tuple:
    """Symbol projections, recorded as the tuple of unary numerals' lengths (meta-level)."""
    return tuple(word.count(s) for s in alphabet)


# ------------------------------------------------- shortlex Knuth-Bendix
def shortlex_key(word: str, order: str):
    rank = {c: i for i, c in enumerate(order)}
    return (len(word), [rank[c] for c in word])


def critical_pairs(r1: Rule, r2: Rule) -> list[tuple[str, str]]:
    (l1, s1), (l2, s2) = r1, r2
    pairs = []
    for k in range(1, min(len(l1), len(l2))):          # proper overlaps
        if l1[-k:] == l2[:k]:
            pairs.append((s1 + l2[k:], l1[:-k] + s2))
    for i in occurrences(l1, l2):                       # inclusions
        if r1 == r2 and i == 0:
            continue
        pairs.append((s1, l1[:i] + s2 + l1[i + len(l2):]))
    return pairs


def knuth_bendix(equations, order: str, max_rules: int = 400, max_steps: int = 50_000,
                 max_word: int = 60):
    """Shortlex Knuth-Bendix completion for a string rewriting system.

    Returns ``(rules, complete)``.  ``complete`` is True only when every
    critical pair has been resolved, in which case ``rules`` is a finite
    convergent system whose normal forms are canonical representatives of
    the congruence generated by ``equations``.
    """
    key = lambda w: shortlex_key(w, order)
    rules: list[Rule] = []
    heap = []
    counter = itertools.count()

    def push(u, v):
        heapq.heappush(heap, (len(u) + len(v), next(counter), u, v))

    for u, v in equations:
        push(u, v)
    steps = 0
    while heap:
        steps += 1
        if steps > max_steps or len(rules) > max_rules:
            return rules, False
        _, _, u, v = heapq.heappop(heap)
        u, v = normal_form(u, rules), normal_form(v, rules)
        if u == v:
            continue
        if key(u) < key(v):
            u, v = v, u
        if len(u) > max_word:
            return rules, False
        new = (u, v)
        # inter-reduce existing rules
        kept = []
        for (l, r) in rules:
            if u in l:
                push(l, r)
            else:
                kept.append((l, normal_form(r, kept + [new]) if u in r else r))
        rules = kept + [new]
        for other in list(rules):
            for cp in critical_pairs(new, other) + (critical_pairs(other, new) if other != new else []):
                push(*cp)
    rules = sorted(set((l, normal_form(r, rules)) for l, r in rules), key=lambda x: (key(x[0]), x[1]))
    return rules, True


def count_irreducible(rules, alphabet: str, max_len: int) -> list[int]:
    """Number of irreducible words of each length 0..max_len (factor-closed enumeration)."""
    lhss = [l for l, _ in rules]
    level = [""]
    counts = [1]
    for _ in range(max_len):
        nxt = []
        for w in level:
            for c in alphabet:
                x = w + c
                if not any(x.endswith(l) for l in lhss):
                    nxt.append(x)
        counts.append(len(nxt))
        level = nxt
        if not level:
            break
    return counts


def irreducible_words(rules, alphabet: str, max_len: int) -> list[str]:
    lhss = [l for l, _ in rules]
    out, level = [""], [""]
    for _ in range(max_len):
        level = [w + c for w in level for c in alphabet if not any((w + c).endswith(l) for l in lhss)]
        out += level
        if not level:
            break
    return out


# ------------------------------------------------ congruence on a finite slice
class UnionFind:
    def __init__(self, items):
        self.parent = {x: x for x in items}

    def find(self, x):
        p = self.parent
        while p[x] != x:
            p[x] = p[p[x]]
            x = p[x]
        return x

    def union(self, a, b):
        ra, rb = self.find(a), self.find(b)
        if ra != rb:
            self.parent[max(ra, rb)] = min(ra, rb)

    def classes(self):
        out = {}
        for x in self.parent:
            out.setdefault(self.find(x), []).append(x)
        return list(out.values())


def length_preserving_classes(relations, alphabet: str, length: int):
    """Exact congruence classes of words of a fixed length, for length-preserving relations.

    Because every relation preserves length, derivations never leave the
    slice of words of this length, so the classes computed here are exact.
    """
    for u, v in relations:
        assert len(u) == len(v), "relations must preserve length"
    ws = list(words(alphabet, length))
    uf = UnionFind(ws)
    for w in ws:
        for u, v in relations:
            for x in one_step(w, [(u, v)]):
                uf.union(w, x)
    return uf.classes()


# ------------------------------------------------ derivations (System A dynamics)
def reachable(word: str, rules, limit: int = 200_000):
    """Breadth-first set of words reachable from ``word``; None if over limit."""
    seen = {word}
    q = deque([word])
    while q:
        w = q.popleft()
        for x in set(one_step(w, rules)):
            if x not in seen:
                seen.add(x)
                if len(seen) > limit:
                    return None
                q.append(x)
    return seen


def derivation_extremes(word: str, rules, limit: int = 200_000, max_len: int | None = None, memo=None):
    """Minimum and maximum number of steps from ``word`` to an irreducible word.

    Returns ``(min, max)``; ``("cycle", w)`` if some derivation revisits ``w``
    (a certificate of non-termination); ``("too_long", w)`` if a reachable word
    exceeds ``max_len``; or ``None`` if more than ``limit`` words were explored.
    Iterative (no recursion limit).  ``memo`` may be shared between calls.
    """
    memo = {} if memo is None else memo
    on_stack: set[str] = set()
    explored = 0
    stack = [(word, None)]
    while stack:
        w, succ = stack[-1]
        if succ is None:
            if w in memo:
                stack.pop()
                continue
            if max_len is not None and len(w) > max_len:
                return ("too_long", w)
            explored += 1
            if explored > limit:
                return None
            succ = sorted(set(one_step(w, rules)))
            stack[-1] = (w, succ)
            on_stack.add(w)
            for x in succ:
                if x in on_stack:
                    return ("cycle", x)
                if x not in memo:
                    stack.append((x, None))
            continue
        # all successors processed
        stack.pop()
        on_stack.discard(w)
        if not succ:
            memo[w] = (0, 0)
        else:
            memo[w] = (1 + min(memo[x][0] for x in succ), 1 + max(memo[x][1] for x in succ))
    return memo[word]
