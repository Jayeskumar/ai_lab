"""EXP-C01-02: congruences on the one-symbol free monoid (emergence of modular counting)."""

import random
from functools import reduce
from math import gcd

from systems.rewriting import UnionFind, count_irreducible, knuth_bendix

META = {
    "id": "EXP-C01-02",
    "cycle": "C01",
    "title": "One-symbol congruences: index and period of finitely generated congruences",
    "agent": "Mathematical Explorer",
    "question": "What structures arise when words over a single symbol a are identified by finitely many "
                "relations a^m = a^n?",
    "hypothesis": "The congruence generated by relations a^{m_i} = a^{n_i} (m_i < n_i) is the monogenic "
                  "congruence with index M = min m_i and period P = gcd(n_i - m_i): exactly M + P classes, "
                  "a^x ~ a^y iff x = y or (x, y >= M and x = y mod P).",
    "assumptions": ["System A, alphabet {a}", "exponents are meta-level names for unary numerals",
                    "relations with 1-3 equations and exponents <= 20"],
    "methodology": "Two independent methods per relation set: (1) shortlex Knuth-Bendix completion, reading "
                   "index/period from the completed single rule and counting irreducible words; (2) union-find "
                   "over exponents 0..B with all shifted relations (B = 6 max n). Compare both with the formula.",
    "falsification": "Any relation set where completion yields a different rule, the class count differs from "
                     "M + P, or the bounded union-find partition of small exponents differs from the formula.",
    "seed": 20261018,
}


def formula_classes(M, P, upto):
    """Class label of each exponent 0..upto under the predicted congruence."""
    return [x if x < M else M + (x - M) % P for x in range(upto + 1)]


def uf_classes(rels, B, upto):
    uf = UnionFind(range(B + 1))
    for m, n in rels:
        for k in range(0, B - n + 1):
            uf.union(m + k, n + k)
    root_label = {}
    labels = []
    for x in range(upto + 1):
        r = uf.find(x)
        labels.append(root_label.setdefault(r, x))
    return labels


def normalise(labels):
    seen = {}
    return [seen.setdefault(l, len(seen)) for l in labels]


def check(rels):
    M = min(m for m, _ in rels)
    P = reduce(gcd, (n - m for m, n in rels))
    eqs = [("a" * m, "a" * n) for m, n in rels]
    rules, complete = knuth_bendix(eqs, "a")
    kb_ok = complete and rules == [("a" * (M + P), "a" * M)]
    counts = count_irreducible(rules, "a", M + P + 2) if complete else None
    count_ok = counts is not None and sum(counts) == M + P
    nmax = max(n for _, n in rels)
    upto = nmax + 5
    uf_ok = normalise(uf_classes(rels, 6 * nmax + 10, upto)) == normalise(formula_classes(M, P, upto))
    return kb_ok and count_ok and uf_ok, {"rels": rels, "M": M, "P": P, "kb_rules": rules, "complete": complete,
                                         "kb_ok": kb_ok, "count_ok": count_ok, "uf_ok": uf_ok}


def run():
    rng = random.Random(META["seed"])
    pairs = [(m, n) for n in range(1, 13) for m in range(0, n)]
    tested, failures = {"one": 0, "two": 0, "three": 0}, []
    for p in pairs:
        ok, info = check([p])
        tested["one"] += 1
        if not ok:
            failures.append(info)
    for i, p in enumerate(pairs):
        for q in pairs[i:]:
            ok, info = check([p, q])
            tested["two"] += 1
            if not ok:
                failures.append(info)
    big = [(m, n) for n in range(1, 21) for m in range(0, n)]
    for _ in range(3000):
        rels = rng.sample(big, 3)
        ok, info = check(rels)
        tested["three"] += 1
        if not ok:
            failures.append(info)
    example = check([(2, 5), (3, 7)])[1]
    return {
        "tested": tested,
        "failures": failures[:20],
        "n_failures": len(failures),
        "worked_example": example,
        "summary": [
            f"relation sets tested: {tested} (exhaustive for 1-2 relations with exponents <= 12; 3000 random "
            f"triples with exponents <= 20)",
            f"failures of the (min, gcd) formula: {len(failures)}",
            f"example a^2=a^5, a^3=a^7 completes to {example['kb_rules']} (index {example['M']}, period {example['P']})",
        ],
    }
